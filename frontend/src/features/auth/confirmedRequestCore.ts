/**
 * Ядро одноразового защищённого запроса с одноразовым кодом
 * (`x-confirmation-*` или challenge/code в теле — `contract.deposit`,
 * `contract.file`, `user.email.change`, `POST /users/me/email/confirm`,
 * `user.password.change`).
 *
 * Общий `authorizedRequest` трактует любой 401 как истёкший access token:
 * делает `refresh` и повторяет тот же запрос, а после второго 401 очищает
 * сессию. Для запроса с кодом это опасно — 401 здесь может значить
 * неверный/просроченный код, а не истёкшую сессию. Тогда код ушёл бы на
 * сервер дважды, а после второй ошибки пользователя выбросило бы из CRM.
 * Точный код ошибки backend для неверного кода в OpenAPI 0.2.0 не описан —
 * поэтому дальнейшая классификация 401 сделана нейтральной (см.
 * `error-messages.ts`), а не безопасность самого повтора: полностью
 * повторный запрос ЗАПРЕЩЁН независимо от причины 401.
 *
 * Тот же приём уже применялся вручную для `POST /confirmations/{id}/confirm`
 * (`src/features/users/api.ts`, `confirmAction`): сначала дешёвое защищённое
 * чтение освежает токен обычным механизмом, затем сам запрос с кодом уходит
 * один раз без повтора. Здесь это вынесено в общий helper, чтобы не
 * дублировать его на каждый новый endpoint.
 *
 * Файл не импортирует ничего (ни `@/...`, ни соседние модули): зависимости —
 * `refresh`/`send` — приходят параметром, поэтому логику можно проверить
 * тестом без сети, без сборки Next.js и без резолва алиасов путей, которого
 * обычный `node --experimental-strip-types` не умеет.
 */
export interface ConfirmedRequestDeps<T> {
  /** Дешёвое защищённое чтение — при необходимости обновит токен обычным `authorizedRequest`. */
  refresh: () => Promise<unknown>
  /** Сам запрос с кодом — ровно один раз, без повтора на 401. */
  send: () => Promise<T>
}

export async function runConfirmedRequest<T>(
  deps: ConfirmedRequestDeps<T>,
): Promise<T> {
  await deps.refresh()

  return deps.send()
}
